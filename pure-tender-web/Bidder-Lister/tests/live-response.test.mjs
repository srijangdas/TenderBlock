import assert from 'node:assert/strict';
import { parseApiJson } from '../src/api/parseApiJson.js';
import { proposalLimitBytes, validateProposal } from '../src/api/proposalValidation.js';
const parsed = parseApiJson('{"content":[{"estimatedValue":9007199254740993.45,"quotedAmount":99999999999999999.99,"number":2}],"totalElements":10}');
assert.equal(parsed.content[0].estimatedValue, '9007199254740993.45');
assert.equal(parsed.content[0].quotedAmount, '99999999999999999.99');
assert.equal(parsed.totalElements, 10);
const description = 'Quotation text: "estimatedValue":9007199254740993.45 and \\ an escaped slash';
assert.equal(parseApiJson(JSON.stringify({description, budget:'100.25'})).description, description);
assert.equal(parseApiJson('{"estimatedValue":1e3}').estimatedValue, '1e3');
assert.equal(parseApiJson('{"estimatedValue":null}').estimatedValue, null);
assert.throws(() => parseApiJson('{"estimatedValue":123broken}'));
assert.equal(proposalLimitBytes(undefined), 1024 * 1024);
assert.equal(proposalLimitBytes('10'), 10 * 1024 * 1024);
for (const value of ['bad', '0', '11', '-1']) assert.equal(proposalLimitBytes(value), 1024 * 1024);
await validateProposal(new File(['%PDF-test'], 'test.pdf', {type:'application/pdf'}), 1024 * 1024);
await assert.rejects(() => validateProposal(new File(['not a PDF'], 'test.pdf', {type:'application/pdf'}), 1024 * 1024), /PDF header/);
await assert.rejects(() => validateProposal(new File(['%PDF-test'], 'test.txt', {type:'text/plain'}), 1024 * 1024), /PDF/);
await assert.rejects(() => validateProposal(new File(['%PDF-'+ 'x'.repeat(1024 * 1024)], 'test.pdf', {type:'application/pdf'}), 1024 * 1024), /1 MB/);
console.log('PASS: exact response money, escaped JSON strings, multipart limits and PDF header validation');
