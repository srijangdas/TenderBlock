import assert from 'node:assert/strict';
import { TEAM_ROUTES, toTeamRegisterRequest, toTeamCompanyProfileRequest, toTeamTenderRequest } from '../src/api/contracts.js';
import { normalizeTender, normalizeTenderList, toCurrentUser } from '../src/api/dtos.js';
const form={fullName:' Test User ',email:'TEST@example.com ',password:'Password123',phoneNumber:'9876543210',organizationName:'Example Co',registrationId:'R123',address:'Jaipur', budget:'50000',title:' Test tender ',description:' Test ',submissionDeadline:'2030-01-01T10:00',openingDate:'2030-01-02T10:00'};
assert.deepEqual(toTeamRegisterRequest(form),{fullName:'Test User',email:'test@example.com',password:'Password123'});
assert.deepEqual(toTeamCompanyProfileRequest(form),{companyName:'Example Co',registrationNumber:'R123',gstin:null,pan:null,address:'Jaipur',contactNumber:'9876543210',website:null});
const tender=toTeamTenderRequest(form);
assert.deepEqual(Object.keys(tender),['title','description','estimatedValue','submissionDeadline','openingDate']);
assert.equal(tender.estimatedValue,'50000');
assert.ok(Date.parse(tender.openingDate)>Date.parse(tender.submissionDeadline));
assert.throws(()=>toTeamTenderRequest({...form,openingDate:'2029-12-01T10:00'}),/opening date/);
assert.equal(TEAM_ROUTES.publishedTenders,'/tenders/published');
assert.equal(TEAM_ROUTES.myTenders,'/tenders/my');
assert.equal(TEAM_ROUTES.register('AUTHORITY'),'/auth/register/AUTHORITY');
const items=normalizeTenderList({content:[{id:'1',title:'Example',estimatedValue:50000,authorityName:'Issuer',status:'SUBMITTED'}]});
assert.equal(items[0].budget,50000);
assert.equal(items[0].department,'Issuer');
assert.equal(items[0].sector,null);
assert.equal(toCurrentUser({userId:'u1',role:'CONTRACTOR',accountStatus:'PENDING'}).verified,false);
assert.equal(toCurrentUser({userId:'u1',role:'AUTHORITY',accountStatus:'VERIFIED'}).role,'LISTER');
console.log('PASS: team branch auth/company/tender JSON, endpoint and response contracts');
